// Generates packages/protocol/src/guide-outline.js: the structure of the
// game's guide (apps/game/js/help.js GUIDE, indexed by js/guide.js
// guideContent) without its texts: the chapters in guide order with their
// steps (id, since, the steps each waits for, parallel, passive, outside),
// the tour's chapter order and the content version. The server computes a
// player's guide progress from it and edits it for the admin guide actions
// (packages/protocol/src/guide.js, docs/accounts-api.md 8.11), so it never
// imports game UI code. CI regenerates it and fails on a difference.
//
//   node tools/gen-guide-outline.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CONTENT } from '../apps/game/js/guide.js';

export const OUTLINE_PATH = fileURLToPath(new URL('../packages/protocol/src/guide-outline.js', import.meta.url));

/** The outline of indexed guide content (guideContent), as plain data. */
export function guideOutline(content = CONTENT) {
  return {
    version: content.version,
    tourOrder: content.tourChapters.map((c) => c.id),
    chapters: content.chapters.map((c) => ({
      id: c.id,
      steps: c.steps.map((s) => {
        const e = content.steps.get(s.id);
        return { id: s.id, since: e.since, after: [...e.after], parallel: s.parallel === true, passive: s.passive === true, outside: s.outside === true };
      }),
    })),
  };
}

/** The text of packages/protocol/src/guide-outline.js. */
export function outlineSource(content = CONTENT) {
  return `// Generated by tools/gen-guide-outline.mjs from apps/game/js/help.js GUIDE: do not edit.
// The guide's structure without its texts: the chapters in guide order with
// their steps (since: the version that added it; after: the steps it waits
// for; parallel, passive, outside as in help.js), the chapters in the tour's
// order and the content version (docs/contracts.md, "The guide and the tour").

const deepFreeze = (v) => {
  if (v && typeof v === 'object') for (const k of Object.keys(v)) deepFreeze(v[k]);
  return Object.freeze(v);
};

export const GUIDE_OUTLINE = deepFreeze(
${JSON.stringify(guideOutline(content), null, 2)}
);
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(OUTLINE_PATH, outlineSource());
  console.log(`wrote ${OUTLINE_PATH}`);
}
