// The self-hosted fonts of the game and the website: Barlow, Barlow
// Condensed and JetBrains Mono, Latin subset, woff2, under the SIL Open Font
// License 1.1. The files come from the Fontsource packages pinned in
// package.json (devDependencies, exact versions, package-lock.json holds
// their integrity hashes); Fontsource builds them from the Google Fonts
// releases of the upstream projects:
//   Barlow, Barlow Condensed  https://github.com/jpt/barlow (OFL 1.1)
//   JetBrains Mono            https://github.com/JetBrains/JetBrainsMono (OFL 1.1)
//
//   node tools/gen-fonts.mjs          copy the files, write the licences and css/fonts.css
//   node tools/gen-fonts.mjs --check  exit 1 when the committed files differ
//
// Output, all in apps/game (the website gets the same files under /lib/,
// tools/build-dist.mjs; the game's own copies are shared there too):
//   fonts/<family>-latin-<weight>.woff2
//   fonts/OFL-<Family>.txt     the licence of each family, with its copyright line
//   css/fonts.css              the @font-face rules
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const GAME = join(root, 'apps/game');

/** The families and weights the design uses (Foundations board): text, titles and labels, numbers. */
export const FAMILIES = Object.freeze([
  { family: 'Barlow', pkg: '@fontsource/barlow', slug: 'barlow', licence: 'OFL-Barlow.txt', weights: [400, 500, 600, 700] },
  { family: 'Barlow Condensed', pkg: '@fontsource/barlow-condensed', slug: 'barlow-condensed', licence: 'OFL-Barlow-Condensed.txt', weights: [500, 600, 700] },
  { family: 'JetBrains Mono', pkg: '@fontsource/jetbrains-mono', slug: 'jetbrains-mono', licence: 'OFL-JetBrains-Mono.txt', weights: [400, 600, 700] },
]);

/** The two faces every first screen shows (body text and titles): preloaded by the pages. */
export const CRITICAL = Object.freeze(['barlow-latin-400.woff2', 'barlow-condensed-latin-700.woff2']);

/** File name of one face in fonts/. */
export const fontFile = (slug, weight) => `${slug}-latin-${weight}.woff2`;

/** The Latin subset's code points, as Fontsource (and Google Fonts) cut it. */
function latinRange(pkgDir) {
  const ranges = JSON.parse(readFileSync(join(pkgDir, 'unicode.json'), 'utf8'));
  if (typeof ranges.latin !== 'string') throw new Error(`${pkgDir}/unicode.json has no latin range`);
  return ranges.latin;
}

function packageDir(pkg) {
  const dir = join(root, 'node_modules', pkg);
  if (!existsSync(join(dir, 'package.json'))) throw new Error(`${pkg} is not installed: run "npm ci --ignore-scripts"`);
  return dir;
}

/** Every output file: `{ path (relative to apps/game), data (Buffer or string) }`. */
export function fontOutputs() {
  const out = [];
  const faces = [];
  for (const f of FAMILIES) {
    const dir = packageDir(f.pkg);
    const { version, license } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    if (license !== 'OFL-1.1') throw new Error(`${f.pkg} is licensed ${license}, expected OFL-1.1`);
    const range = latinRange(dir);
    for (const w of f.weights) {
      const src = join(dir, 'files', `${f.slug}-latin-${w}-normal.woff2`);
      const data = readFileSync(src);
      // woff2 signature: "wOF2".
      if (data.subarray(0, 4).toString('latin1') !== 'wOF2') throw new Error(`${src} is not a woff2 file`);
      out.push({ path: `fonts/${fontFile(f.slug, w)}`, data });
      faces.push({ family: f.family, weight: w, file: fontFile(f.slug, w), range });
    }
    const text = readFileSync(join(dir, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n').trimEnd();
    out.push({
      path: `fonts/${f.licence}`,
      data: `${f.family}: the woff2 files fonts/${f.slug}-latin-*.woff2 of WebRA come from the Fontsource package ${f.pkg} ${version} (Latin subset), unchanged.\n\n${text}\n`,
    });
  }
  const rules = faces
    .map(
      (f) =>
        `@font-face {\n  font-family: '${f.family}';\n  font-style: normal;\n  font-weight: ${f.weight};\n  font-display: swap;\n  src: url('../fonts/${f.file}') format('woff2');\n  unicode-range: ${f.range};\n}`,
    )
    .join('\n\n');
  out.push({
    path: 'css/fonts.css',
    data:
      '/* Generated by tools/gen-fonts.mjs: do not edit. The game\'s fonts, self-hosted\n' +
      '   (the CSP allows fonts from this site only): Barlow, Barlow Condensed and\n' +
      '   JetBrains Mono, Latin subset, SIL Open Font License 1.1 (fonts/OFL-*.txt).\n' +
      '   css/theme.css names them in --ui-font, --ui-font-display and --ui-font-mono.\n' +
      '   The website loads this sheet from /lib/css/fonts.css; tools/build-dist.mjs\n' +
      '   points the game\'s copy at the same /lib/fonts/ files, so both share one cache. */\n\n' +
      `${rules}\n`,
  });
  return out;
}

const same = (a, b) => (typeof a === 'string' ? a === b.toString('utf8') : Buffer.compare(a, b) === 0);

/** Paths (relative to apps/game) whose committed copy differs from the generated one. */
export function staleFonts(gameDir = GAME) {
  return fontOutputs()
    .filter(({ path, data }) => {
      const file = join(gameDir, path);
      return !existsSync(file) || !same(data, readFileSync(file));
    })
    .map((o) => o.path);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const stale = staleFonts();
    if (stale.length) {
      console.error(`gen-fonts: out of date: ${stale.join(', ')}. Run "node tools/gen-fonts.mjs".`);
      process.exit(1);
    }
    console.log('gen-fonts: fonts and css/fonts.css are up to date');
  } else {
    const outputs = fontOutputs();
    for (const { path, data } of outputs) {
      const file = join(GAME, path);
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, data);
    }
    console.log(`gen-fonts: wrote ${outputs.length} files to apps/game (fonts/, css/fonts.css)`);
  }
}
